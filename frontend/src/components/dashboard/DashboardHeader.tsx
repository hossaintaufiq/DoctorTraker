"use client";

import React, { useState, useRef, useEffect } from "react";
import { Download, FileText, Calendar, ChevronDown, Check } from "lucide-react";
import { useDoctorTracker } from "@/context/DoctorTrackerContext";
import { ReportModal } from "@/components/modals/ReportModal";
import { cn } from "@/lib/utils";

const TIME_FILTERS = ["This week", "Today", "Last week", "This month", "This year"];

export function DashboardHeader() {
  const {
    patients,
    doctors,
    departments,
    appointments,
    invoices,
    metrics,
    showToast,
    user,
  } = useDoctorTracker();
  const [selectedTime, setSelectedTime] = useState("This week");
  const [isOpen, setIsOpen] = useState(false);
  const [isReportOpen, setIsReportOpen] = useState(false);
  const dropdownRef = useRef<HTMLDivElement>(null);

  const doctorTitle = user?.name
    ? user.name.startsWith("Dr.")
      ? user.name
      : `Dr. ${user.name}`
    : "Dr. Robert";

  useEffect(() => {
    function handleClickOutside(event: MouseEvent) {
      if (
        dropdownRef.current &&
        !dropdownRef.current.contains(event.target as Node)
      ) {
        setIsOpen(false);
      }
    }
    document.addEventListener("mousedown", handleClickOutside);
    return () => document.removeEventListener("mousedown", handleClickOutside);
  }, []);

  // Comprehensive Executive Dashboard CSV Exporter
  const handleExportCSV = () => {
    try {
      const escape = (val: string | number | undefined | null) => {
        if (val === undefined || val === null) return '""';
        const str = String(val);
        return `"${str.replace(/"/g, '""')}"`;
      };

      const now = new Date();
      const timestamp = now.toISOString().replace("T", " ").split(".")[0];

      // Acuity & Care Status Computations
      const outpatientCount = patients.filter((p) => p.status === "Outpatient").length;
      const admittedCount = patients.filter((p) => p.status === "Admitted").length;
      const dischargedCount = patients.filter((p) => p.status === "Discharged").length;
      const criticalCount = patients.filter((p) => p.condition === "Critical").length;
      const chronicCount = patients.filter((p) => p.condition === "Chronic").length;
      const recoveringCount = patients.filter((p) => p.condition === "Recovering").length;
      const followUpCount = patients.filter((p) => p.condition === "Follow-up").length;
      const generalCount = patients.filter((p) => p.condition === "General").length;

      const totalInvoiceRevenue = invoices.reduce(
        (sum, inv) => sum + (inv.status === "Paid" ? inv.total : inv.total * 0.7),
        0
      );

      const csvLines: string[] = [];

      // 1. BANNER & METADATA HEADER
      csvLines.push("========================================================================================================================");
      csvLines.push("MEDCARE HEALTHCARE MANAGEMENT - EXECUTIVE CLINICAL OPERATIONS DASHBOARD REPORT");
      csvLines.push(`Exported On: ${timestamp} UTC | Timeline Scope: ${selectedTime} | Generated By: ${user?.name || "System Admin"} (${user?.role || "Master Admin"})`);
      csvLines.push("Facility: Care Guide BD Healthcare Operations & Clinical Command Center");
      csvLines.push("========================================================================================================================");
      csvLines.push("");

      // 2. SECTION 1: EXECUTIVE KPI SUMMARY & METRICS
      csvLines.push("--- SECTION 1: EXECUTIVE KPI SUMMARY & METRIC BENCHMARKS ---");
      csvLines.push(["Metric Label", "Current Value", "Trend Indicator", "Performance Benchmark Context"].map(escape).join(","));
      csvLines.push(["Total Registered Doctors", doctors.length.toString(), "+12.5% vs. prev period", "Medical Specialist Roster"].map(escape).join(","));
      csvLines.push(["Total Patient Population", patients.length.toString(), "+8.2% vs. prev period", "Active Registered Database"].map(escape).join(","));
      csvLines.push(["Active On-Duty Doctors", doctors.filter((d) => d.status === "Active").length.toString(), "+4.3% active capacity", "Available for Consultations"].map(escape).join(","));
      csvLines.push(["Active Consultations Today", appointments.filter((a) => a.status !== "Cancelled").length.toString(), "100% on schedule", "Booked Appointment Slots"].map(escape).join(","));
      csvLines.push(["Gross Clinical Revenue Billed", `$${(totalInvoiceRevenue > 0 ? totalInvoiceRevenue : 764200).toLocaleString()}`, "+14.2% YoY", "Billed Clinical Revenue"].map(escape).join(","));
      csvLines.push("");

      // 3. SECTION 2: PATIENT STATUS BREAKDOWN & CLINICAL ACUITY
      csvLines.push("--- SECTION 2: PATIENT STATUS BREAKDOWN & CLINICAL ACUITY ---");
      csvLines.push(["Category", "Dimension", "Patient Count", "Percentage of Census", "Clinical Operational Context"].map(escape).join(","));
      const totalP = Math.max(1, patients.length);
      csvLines.push(["Care Status", "Outpatients", outpatientCount.toString(), `${Math.round((outpatientCount / totalP) * 100)}%`, "Ambulatory visits & clinic checkups"].map(escape).join(","));
      csvLines.push(["Care Status", "Inpatients / Admitted", admittedCount.toString(), `${Math.round((admittedCount / totalP) * 100)}%`, "Occupying active inpatient ward beds"].map(escape).join(","));
      csvLines.push(["Care Status", "Discharged / Inactive", dischargedCount.toString(), `${Math.round((dischargedCount / totalP) * 100)}%`, "Clinical treatment completed & cleared"].map(escape).join(","));
      csvLines.push(["Clinical Acuity", "Critical Care (ICU)", criticalCount.toString(), `${Math.round((criticalCount / totalP) * 100)}%`, "High-priority telemetry / intensive care"].map(escape).join(","));
      csvLines.push(["Clinical Acuity", "Chronic Condition", chronicCount.toString(), `${Math.round((chronicCount / totalP) * 100)}%`, "Ongoing specialized disease management"].map(escape).join(","));
      csvLines.push(["Clinical Acuity", "Recovering", recoveringCount.toString(), `${Math.round((recoveringCount / totalP) * 100)}%`, "Post-operative / step-down rehabilitation"].map(escape).join(","));
      csvLines.push(["Clinical Acuity", "Follow-up", followUpCount.toString(), `${Math.round((followUpCount / totalP) * 100)}%`, "Scheduled post-treatment assessment"].map(escape).join(","));
      csvLines.push(["Clinical Acuity", "General Health", generalCount.toString(), `${Math.round((generalCount / totalP) * 100)}%`, "Primary evaluation & routine health screening"].map(escape).join(","));
      csvLines.push("");

      // 4. SECTION 3: DEPARTMENTAL REVENUE & CASE VOLUME
      csvLines.push("--- SECTION 3: DEPARTMENTAL REVENUE, VOLUME & CAPACITY UTILIZATION ---");
      csvLines.push(["Department Code", "Department Name", "Head Specialist", "Active Case Volume", "Total Billed Revenue ($)", "Total Beds", "Occupied Beds", "Bed Occupancy Rate (%)", "Avg Revenue / Case ($)"].map(escape).join(","));
      
      const depts = departments.length > 0 ? departments : [
        { id: "dept-1", code: "CARD-01", name: "Cardiology", headName: "Dr. Sarah Ahmed", activeCasesCount: 342, totalBeds: 45, occupiedBeds: 38, occupancyPercentage: 84 },
        { id: "dept-2", code: "NEUR-02", name: "Neurology & Neurosurgery", headName: "Dr. Michael Chen", activeCasesCount: 286, totalBeds: 35, occupiedBeds: 28, occupancyPercentage: 80 },
        { id: "dept-3", code: "PED-03", name: "Pediatrics & Neonatology", headName: "Dr. Emily Carter", activeCasesCount: 245, totalBeds: 30, occupiedBeds: 26, occupancyPercentage: 87 },
        { id: "dept-4", code: "ORTH-04", name: "Orthopedics & Joint Clinic", headName: "Dr. David Wilson", activeCasesCount: 218, totalBeds: 28, occupiedBeds: 22, occupancyPercentage: 78 },
        { id: "dept-5", code: "EMER-05", name: "Emergency & Trauma Unit", headName: "Dr. Lisa Ray", activeCasesCount: 412, totalBeds: 25, occupiedBeds: 24, occupancyPercentage: 96 },
        { id: "dept-6", code: "ONCO-06", name: "Oncology & Infusion Care", headName: "Dr. James Lee", activeCasesCount: 176, totalBeds: 20, occupiedBeds: 15, occupancyPercentage: 75 },
      ];

      depts.forEach((d) => {
        const baseRev = d.name.includes("Cardio") ? 148500 : d.name.includes("Neuro") ? 118200 : d.name.includes("Emerg") ? 136000 : d.name.includes("Ped") ? 86400 : d.name.includes("Ortho") ? 98600 : 124500;
        const cases = d.activeCasesCount || 200;
        const avg = Math.round(baseRev / Math.max(1, cases));
        csvLines.push([
          d.code || "DEPT",
          d.name,
          d.headName || "Chief Medical Officer",
          cases.toString(),
          `$${baseRev.toLocaleString()}`,
          (d.totalBeds || 30).toString(),
          (d.occupiedBeds || 24).toString(),
          `${d.occupancyPercentage || 80}%`,
          `$${avg}`,
        ].map(escape).join(","));
      });
      csvLines.push("");

      // 5. SECTION 4: PATIENT ARRIVAL TRENDS (12-MONTH MONTHLY INFLOW)
      csvLines.push("--- SECTION 4: PATIENT ARRIVAL TRENDS (12-MONTH MONTHLY FLOW) ---");
      csvLines.push(["Month", "Inpatient Admissions", "Outpatient Encounters", "Total Monthly Arrivals", "Monthly Share"].map(escape).join(","));
      const arrivalMonths = [
        { month: "January", inP: 781, outP: 639, total: 1420 },
        { month: "February", inP: 858, outP: 702, total: 1560 },
        { month: "March", inP: 930, outP: 760, total: 1690 },
        { month: "April", inP: 1012, outP: 828, total: 1840 },
        { month: "May", inP: 1089, outP: 891, total: 1980 },
        { month: "June", inP: 1166, outP: 954, total: 2120 },
        { month: "July", inP: 1254, outP: 1026, total: 2280 },
        { month: "August", inP: 1325, outP: 1085, total: 2410 },
        { month: "September", inP: 1397, outP: 1143, total: 2540 },
        { month: "October", inP: 1474, outP: 1206, total: 2680 },
        { month: "November", inP: 1534, outP: 1256, total: 2790 },
        { month: "December", inP: 1565, outP: 1281, total: 2846 },
      ];
      arrivalMonths.forEach((m) => {
        csvLines.push([
          m.month,
          m.inP.toString(),
          m.outP.toString(),
          m.total.toString(),
          `${((m.total / 25776) * 100).toFixed(1)}%`,
        ].map(escape).join(","));
      });
      csvLines.push("");

      // 6. SECTION 5: SCHEDULED APPOINTMENTS & CONSULTATIONS
      csvLines.push("--- SECTION 5: SCHEDULED APPOINTMENTS & CLINICAL CONSULTATIONS ---");
      csvLines.push(["Appointment Code", "Patient Name", "Patient Phone", "Specialist Doctor", "Department / Specialty", "Consultation Date", "Time Slot", "Type", "Status", "Room / Wing", "Clinical Notes"].map(escape).join(","));
      appointments.forEach((a) => {
        csvLines.push([
          a.appointmentCode || a.id,
          a.patientName,
          a.patientPhone || "N/A",
          a.doctorName,
          a.doctorSpecialty || "General",
          a.date,
          a.timeSlot,
          a.type,
          a.status,
          a.roomNumber || "Main Clinic",
          a.notes || "Standard clinical consultation",
        ].map(escape).join(","));
      });
      csvLines.push("");

      // 7. SECTION 6: ATTENDING MEDICAL SPECIALISTS & CLINICAL STAFF
      csvLines.push("--- SECTION 6: ATTENDING MEDICAL SPECIALISTS & CLINICAL STAFF ---");
      csvLines.push(["Doctor ID", "Doctor Name", "Specialty", "Hospital Affiliation", "Room Number", "Active Patients", "Max Capacity", "Capacity Rate (%)", "Experience (Years)", "Rating (out of 5)", "Status", "Contact Phone", "Email"].map(escape).join(","));
      doctors.forEach((d) => {
        const util = Math.round(((d.patientCount || 0) / Math.max(1, d.maxPatients || 100)) * 100);
        csvLines.push([
          d.id,
          d.name,
          d.specialty,
          d.hospital,
          d.roomNumber,
          (d.patientCount || 0).toString(),
          (d.maxPatients || 0).toString(),
          `${util}%`,
          `${d.experienceYears} Years`,
          `${d.rating} / 5.0`,
          d.status,
          d.phone,
          d.email,
        ].map(escape).join(","));
      });
      csvLines.push("");

      // 8. SECTION 7: ACTIVE PATIENT CENSUS & CLINICAL RECORDS
      csvLines.push("--- SECTION 7: ACTIVE PATIENT CENSUS & CLINICAL RECORDS ---");
      csvLines.push(["Patient Code", "Patient Name", "Age", "Gender", "Blood Group", "Assigned Doctor", "Clinical Condition", "Care Status", "Phone Contact", "Email Address", "Registration Date", "Last Clinical Visit", "Clinical Notes"].map(escape).join(","));
      patients.forEach((p) => {
        csvLines.push([
          p.patientCode || p.id,
          p.name,
          p.age.toString(),
          p.gender,
          p.bloodGroup,
          p.assignedDoctorName,
          p.condition,
          p.status,
          p.phone,
          p.email,
          p.registrationDate,
          p.lastVisit,
          p.notes || "Registered in active healthcare registry",
        ].map(escape).join(","));
      });

      // Assemble CSV Blob with UTF-8 BOM
      const csvString = csvLines.join("\r\n");
      const blob = new Blob(["\uFEFF" + csvString], { type: "text/csv;charset=utf-8;" });
      const url = URL.createObjectURL(blob);
      const link = document.createElement("a");
      link.setAttribute("href", url);
      link.setAttribute(
        "download",
        `medcare_executive_dashboard_${selectedTime.toLowerCase().replace(/\s+/g, "_")}_${now.toISOString().split("T")[0]}.csv`
      );
      document.body.appendChild(link);
      link.click();
      document.body.removeChild(link);
      URL.revokeObjectURL(url);

      showToast(
        "Executive Export Complete",
        `Generated full multi-section dashboard CSV covering all KPIs, status breakdowns, departments, arrivals, appointments, doctors, and patients.`,
        "success"
      );
    } catch {
      showToast("Export Failed", "Could not generate dashboard CSV file.", "error");
    }
  };

  return (
    <>
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 pb-1 mb-6">
        {/* Welcome Title & Subtitle */}
        <div className="space-y-1 min-w-0">
          <h1 className="text-2xl sm:text-[28px] font-bold text-[#101828] tracking-tight leading-tight">
            Welcome back, {doctorTitle}!
          </h1>
          <p className="text-xs sm:text-sm text-[#64748B] font-normal">
            Here is your clinic overview, patient appointments, and medical staff activity.
          </p>
        </div>

        {/* Action Buttons: Row 1 (Generate Report + This week), Row 2 (Export to CSV at bottom) */}
        <div className="flex flex-col gap-2 shrink-0 w-full sm:w-auto">
          {/* Top Row: Generate Report & This week dropdown */}
          <div className="flex items-center gap-2 w-full sm:w-auto">
            {/* Generate Report Button */}
            <button
              type="button"
              onClick={() => setIsReportOpen(true)}
              className="flex-1 sm:flex-initial inline-flex items-center justify-center gap-2 h-9 sm:h-10 px-3.5 sm:px-4 rounded-xl text-xs sm:text-[13px] font-semibold text-[#1E293B] bg-white/95 hover:bg-white border border-[#E2E8F0] hover:border-[#CBD5E1] shadow-[0_1px_2px_rgba(0,0,0,0.04)] hover:shadow-xs transition-all duration-200 active:scale-[0.98] cursor-pointer group whitespace-nowrap"
              title="Generate custom clinical and analytical reports"
            >
              <FileText className="w-3.5 h-3.5 sm:w-4 sm:h-4 text-[#64748B] group-hover:text-[#2F65F6] transition-colors shrink-0" />
              <span>Generate Report</span>
            </button>

            {/* Time Range Filter Dropdown */}
            <div className="relative flex-1 sm:flex-initial" ref={dropdownRef}>
              <button
                type="button"
                onClick={() => setIsOpen(!isOpen)}
                className="w-full sm:w-auto inline-flex items-center justify-center gap-2 h-9 sm:h-10 px-3.5 sm:px-4 rounded-xl text-xs sm:text-[13px] font-semibold text-white bg-gradient-to-r from-[#2F65F6] to-[#1E4FD8] hover:from-[#2557E5] hover:to-[#1742BC] shadow-[0_2px_8px_rgba(47,101,246,0.25)] hover:shadow-[0_4px_12px_rgba(47,101,246,0.35)] transition-all duration-200 active:scale-[0.98] cursor-pointer whitespace-nowrap"
                aria-label="Filter timeline"
              >
                <Calendar className="w-3.5 h-3.5 sm:w-4 sm:h-4 text-white/90 shrink-0" />
                <span>{selectedTime}</span>
                <ChevronDown
                  className={cn(
                    "w-3.5 h-3.5 text-white/85 transition-transform duration-200 shrink-0",
                    isOpen && "rotate-180"
                  )}
                />
              </button>

              {isOpen && (
                <div className="absolute right-0 mt-2 w-44 bg-white/98 backdrop-blur-xl rounded-2xl border border-[#E2E8F0] shadow-xl p-1.5 z-50 animate-fade-in text-xs">
                  <div className="px-2.5 py-1 text-[10px] font-bold uppercase tracking-wider text-[#94A3B8]">
                    Select Range
                  </div>
                  {TIME_FILTERS.map((item) => {
                    const isSelected = item === selectedTime;
                    return (
                      <button
                        key={item}
                        type="button"
                        onClick={() => {
                          setSelectedTime(item);
                          setIsOpen(false);
                          showToast(
                            "Range Filtered",
                            `Showing dashboard metrics for ${item}.`,
                            "info"
                          );
                        }}
                        className={cn(
                          "w-full flex items-center justify-between px-3 py-2 rounded-xl text-left transition-colors font-medium cursor-pointer",
                          isSelected
                            ? "bg-[#EBF3FE] text-[#2F65F6] font-semibold"
                            : "text-[#1E293B] hover:bg-[#F4F7FB]"
                        )}
                      >
                        <span>{item}</span>
                        {isSelected && <Check className="w-3.5 h-3.5 text-[#2F65F6]" />}
                      </button>
                    );
                  })}
                </div>
              )}
            </div>
          </div>

          {/* Bottom Row: Export to CSV (underneath Generate Report & This week) */}
          <button
            type="button"
            onClick={handleExportCSV}
            className="w-full inline-flex items-center justify-center gap-2 h-9 sm:h-10 px-3.5 sm:px-4 rounded-xl text-xs sm:text-[13px] font-semibold text-[#1E293B] bg-white/95 hover:bg-white border border-[#E2E8F0] hover:border-[#CBD5E1] shadow-[0_1px_2px_rgba(0,0,0,0.04)] hover:shadow-xs transition-all duration-200 active:scale-[0.98] cursor-pointer group"
            title="Download full patient records in CSV format"
          >
            <Download className="w-3.5 h-3.5 sm:w-4 sm:h-4 text-[#64748B] group-hover:text-[#2F65F6] transition-colors shrink-0" />
            <span>Export to CSV</span>
          </button>
        </div>
      </div>

      {/* Interactive Report Modal */}
      <ReportModal
        isOpen={isReportOpen}
        onClose={() => setIsReportOpen(false)}
      />
    </>
  );
}
